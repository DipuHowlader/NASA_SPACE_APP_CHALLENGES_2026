#!/usr/bin/env python3
"""
build_dataset.py — Data preparation step 2
Merges NASA POWER climate features (data/climate_power.json) with curated
geology/terrain attributes (data/sites_earth.json) into one model-ready
dataset, and generates the runtime JS module used by the API.

  python scripts/build_dataset.py

Outputs:
  data/dataset.json       full merged dataset (humans + training)
  lib/data/sites.mjs      ES-module copy consumed by the Vercel API
"""

import json
import pathlib
import datetime as dt

ROOT = pathlib.Path(__file__).resolve().parent.parent
DATA = ROOT / "data"
LIB = ROOT / "lib" / "data"

CLIMATE_KEYS = [
    "temp_mean_c", "temp_max_c", "temp_min_c", "diurnal_range_c",
    "precip_mm_yr", "wind_mean_ms", "rh_min_pct", "solar_kwh_m2_day",
]
CURATED_KEYS = [
    "relief_m", "barrenness",
] + [
    "volcanic_basalt", "impact_crater", "aeolian_dunes", "salt_flat",
    "permafrost_ice", "subsurface_cave", "fluvial_paleolake",
    "hydrothermal_acid", "ophiolite_olivine", "extremophile_studies",
]
# elevation is kept as context (display only) — absolute elevation is not
# comparable between Earth and Mars/Moon, so it is excluded from scoring.
CONTEXT_KEYS = ["elevation_m"]

FEATURE_KEYS = CLIMATE_KEYS + CURATED_KEYS + CONTEXT_KEYS


def main() -> None:
    sites_doc = json.loads((DATA / "sites_earth.json").read_text(encoding="utf-8"))
    power_doc = json.loads((DATA / "climate_power.json").read_text(encoding="utf-8"))
    climate = power_doc["climate"]

    sites_out = []
    missing = []
    for s in sites_doc["sites"]:
        c = climate.get(s["key"])
        if c is None:
            missing.append(s["key"])
            continue
        features = {}
        for k in FEATURE_KEYS:
            if k in CLIMATE_KEYS:
                features[k] = c.get(k)
            elif k in sites_doc["meta"]["tag_definitions"]:
                features[k] = s.get("tags", {}).get(k, 0.0)
            else:
                features[k] = s.get(k)
        sites_out.append({**s, "features": features})

    if missing:
        raise SystemExit(f"ERROR: no POWER climate data for: {missing} — rerun scripts/fetch_power.mjs")

    dataset = {
        "meta": {
            "generated_at": dt.datetime.now(dt.timezone.utc).isoformat(timespec="seconds"),
            "n_sites": len(sites_out),
            "feature_keys": FEATURE_KEYS,
            "climate_features": CLIMATE_KEYS,
            "curated_features": CURATED_KEYS,
            "context_only_features": CONTEXT_KEYS,
            "climate_source": power_doc["meta"]["source"],
            "climate_period": power_doc["meta"]["period"],
        },
        "sites": sites_out,
    }

    (DATA / "dataset.json").write_text(json.dumps(dataset, indent=2), encoding="utf-8")

    LIB.mkdir(parents=True, exist_ok=True)
    (LIB / "sites.mjs").write_text(
        "// AUTO-GENERATED by scripts/build_dataset.py — do not edit.\n"
        f"// Generated {dataset['meta']['generated_at']}\n"
        "export default " + json.dumps({"sites": sites_out}, ensure_ascii=False) + ";\n",
        encoding="utf-8",
    )

    print(f"Built dataset: {len(sites_out)} sites x {len(FEATURE_KEYS)} features")
    print(f"  -> data/dataset.json")
    print(f"  -> lib/data/sites.mjs")


if __name__ == "__main__":
    main()
